import json,glob,re,sys
M={"استرجاع التعلّم السابق":"🔁 نتذكّر معًا","التهيئة وربط الدرس بالمعرفة السابقة":"✨ لحظة فضول","توضيح ناتج التعلّم ومعايير النجاح":"🎯 وجهتنا اليوم",
"تهيئة المفردات والمعرفة اللازمة":"🔑 كلمات مفتاحية","تقديم النص":"📖 رحلة في النص","التعليم الصريح والنمذجة: «أنا أطبّق»":"👩‍🏫 شاهدني أطبّق",
"الممارسة الْمُوجّهة: «نطبّق معًا»":"🤝 نطبّق معًا","تحقّق قبل العمل المستقل":"🚦 إشارة الانطلاق","التطبيق المستقل والأنشطة المتمايزة: «أطبّق بنفسي»":"🚀 تحدّي المستويات",
"التغذية الراجعة وتحسين العمل":"🔍 عين الناقد","بطاقة الخروج الفردية":"🎟️ تذكرة الخروج","غلق الدرس والتأمل في التعلّم":"🪞 مرآة التعلّم","التكليف المنزلي":"🏠 رسالتي إلى البيت",
"التهيئة واستدعاء التعلّم السابق":"✨ نبدأ بحماس","مسار التعلّم وناتج اليوم":"🎯 وجهتنا اليوم","المفردات البصرية":"🖼️ كلمات نراها","نمذجة المعلّم: «أنا أفعل»":"👩‍🏫 شاهدني",
"الممارسة الْمُوجّهة: «نحن نفعل معًا»":"🤝 معًا خطوة خطوة","الممارسة التكيفية: «نحن نفعل»":"🎲 نتدرّب ونلعب","التقييم السريع للجاهزية":"🚦 هل أنا جاهز؟",
"العمل المستقل: «أنت تفعل»":"🚀 دوري الآن","الجسر إلى الكتابة":"✍️ من الكلام إلى الكتابة","التأمل الذاتي والتقويم الختامي":"🪞 مرآة التعلّم"}
n=0;files=0;miss=set()
for f in glob.glob((sys.argv[1] if len(sys.argv)>1 else 'resources/slides')+'/*.json'):
    d=json.load(open(f)); ch=False
    for s in d['slides']:
        for e in s['els']:
            if e['k']!='text': continue
            m=re.match(r'^المرحلة\s*\d+\s*من\s*\d+\s*·\s*(.+)$',e['text'])
            if not m: continue
            st=m.group(1).strip()
            if st not in M: miss.add(st); continue
            e['text']=M[st]; e['x'],e['w']=410,461; e['size']=23
            s['n']=f'[{st}] '+(s.get('n') or ''); n+=1; ch=True
    if ch: files+=1; json.dump(d,open(f,'w'),ensure_ascii=False)
print(n,files,miss)
