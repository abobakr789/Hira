def fd(t, lesson):
    rows = D[lesson]
    m = re.search(r'<section class="sl"[^>]*id="quickn".*?</section>', t, re.S)
    s = m.group(0)
    qr = list(re.finditer(r'<div class="qrow".*?</button></div>', s, re.S))
    assert len(qr) == len(rows), (lesson, len(qr))
    out, pos = [], 0
    for r, new in zip(qr, rows):
        row = r.group(0)
        spans = list(re.finditer(r'<span class="(qok|)"([^>]*)>(.*?color:#3E4A5C">)(.*?)(</span></span>)', row, re.S))
        assert len(spans) == 3, lesson
        assert [bool(x.group(1)) for x in spans] == [n is None for n in new], (lesson, row[:80])
        rr, p = [], 0
        for sp, n in zip(spans, new):
            rr.append(row[p:sp.start(4)]); rr.append(sp.group(4) if n is None else n); p = sp.end(4)
        rr.append(row[p:])
        out.append(s[pos:r.start()]); out.append(''.join(rr)); pos = r.end()
    out.append(s[pos:])
    return t[:m.start()] + ''.join(out) + t[m.end():]

